"""Fake SAP GUI COM layer -- a stand-in for the scripting object graph.

This sits beneath ``RealSapBackend`` at the true outer boundary: it quacks
like the SAPGUI scripting object graph

    application.Children(0) -> connection.Children(0) -> session
    session.findById(path) -> element
    session.Info.Transaction / session.Busy

so ``RealSapBackend`` needs no special-casing, the real adapter is
exercised in tests, and the app can offer a "Fake SAP" mode on a machine
that also runs real SAP.

Structure lives here (Python); the scenario data lives in
``config/fake_sap_scenarios.json`` (generated by
``scripts/generate_fake_scenarios.py``); behaviour lives in the SAP
scripts in ``config/toolbar_config.json``, untouched.
"""

from __future__ import annotations

import json
import logging
from pathlib import Path
from typing import Any

# COM-shaped method names (Children/Info/Busy/findById) must stay as-is.
# ruff: noqa: N802

logger = logging.getLogger("fake_com")

_SCENARIO_PATH = Path(__file__).resolve().parent.parent / "config" / "fake_sap_scenarios.json"

# SAP GUI Scripting methods used by the button scripts. Anything else is a
# property read (see FakeElement.__getattr__). An unmodelled *call* therefore
# fails loudly instead of silently no-oping; an unmodelled *read* falls back
# to "" (mirroring win32com's empty dispatch result).
_METHOD_NAMES = {
    "clickcurrentcell",
    "doubleclickcurrentcell",
    "extractdata",
    "getcellvalue",
    "maximize",
    "modifycell",
    "press",
    "pressenter",
    "presstoolbarbutton",
    "populategridview",
    "select",
    "sendvkey",
    "setfocus",
}

_GRID_MARKER = "shellcont/shell"

# Marker on the ALV toolbar's export button. When the scenario nulls a
# transaction's grid the result list is absent, so this control (and the
# export dialog that follows it) does not exist -- exactly what makes the
# "no data" branch in tools/purchase_request.py reachable.
_EXPORT_BUTTON_MARKER = "tbar[1]/btn[45]"

_MISSING = object()


class FakeComError(RuntimeError):
    """Raised when a control the scenario marks absent is looked up."""


def load_scenario(path=None) -> dict:
    """Load a generated fake scenario (defaults to the committed artifact)."""
    scenario_path = Path(path) if path else _SCENARIO_PATH
    with open(scenario_path, encoding="utf-8") as f:
        return json.load(f)


class FakeComClient:
    """Zero-arg callable returning the fake scripting engine.

    ``RealSapBackend(app_factory=FakeComClient())`` then attaches through the
    same code path as real COM. Accepts an in-memory scenario dict (tests
    build an overridden one to mark a grid absent) or a scenario path.
    """

    def __init__(self, scenario: dict | str | None = None):
        if isinstance(scenario, dict):
            self._scenario = scenario
        else:
            self._scenario = load_scenario(scenario)

    def __call__(self):
        return FakeApplication(self._scenario)

    def get_scripting_engine(self):
        return self()


class FakeApplication:
    def __init__(self, scenario: dict):
        self._connection = FakeConnection(scenario)

    def Children(self, index: int):
        return self._connection


class FakeConnection:
    def __init__(self, scenario: dict):
        self._session = FakeSession(scenario)

    def Children(self, index: int):
        return self._session


class FakeInfo:
    def __init__(self, session: FakeSession):
        self._session = session

    @property
    def Transaction(self) -> str:
        return self._session.current_transaction or ""


class FakeSession:
    """Session-shaped state: current transaction, exported file, grid data."""

    def __init__(self, scenario: dict):
        self._scenario = scenario
        self._datasets: dict = scenario.get("datasets", {})
        self._transactions: dict = scenario.get("transactions", {})
        self._defaults: dict = scenario.get("defaults", {})
        self.current_transaction: str | None = None
        self.last_export_file: str | None = None
        # Read sites that hit the "[mock] ..." fallback. The coverage test
        # asserts this stays empty so a script change can't silently starve
        # the fake of a response.
        self.misses: list[tuple[str, str]] = []

        self._dy_path: str | None = None
        self._dy_filename: str | None = None
        self._upload_filename: str | None = None
        self._info = FakeInfo(self)
        self._elements: dict[str, FakeElement] = {}

    # -- object graph -----------------------------------------------------
    @property
    def Info(self) -> FakeInfo:
        return self._info

    @property
    def Busy(self) -> bool:
        return False

    def findById(self, path: str) -> FakeElement:
        if self._path_absent(path):
            raise FakeComError(f"Control not found: {path}")
        element = self._elements.get(path)
        if element is None:
            element = FakeElement(self, path)
            self._elements[path] = element
        return element

    # -- writes -----------------------------------------------------------
    def write_property(self, path: str, member: str, value: Any) -> None:
        m = member.lower()
        p = path.lower()
        if m == "text" and "okcd" in p and isinstance(value, str) and value.startswith("/n"):
            self.current_transaction = value[2:].strip()
            return
        if m == "text" and "dy_path" in p:
            self._dy_path = value
            return
        if m == "text" and "dy_filename" in p:
            self._dy_filename = value
            if (self.current_transaction or "").upper() == "IW32":
                self._upload_filename = value
            # Only a text export is written to disk. A file dialog for an
            # upload/download (picture or PDF) also sets DY_PATH/DY_FILENAME,
            # but writing the grid there would clobber the real file.
            if self._dy_path and str(value).lower().endswith(".txt"):
                self.last_export_file = self._write_export(
                    self.export_rows(), self._dy_path, self._dy_filename
                )
            return
        # Every other assignment (selected, key, caretPosition, current cell,
        # text into an input field, ...) is accepted and ignored: the engine
        # only cares that the call succeeded.

    # -- reads ------------------------------------------------------------
    def read_property(self, path: str, member: str) -> Any:
        m = member.lower()
        p = path.lower()
        if "sbar" in p:
            return self._sbar_value(m)
        if m == "rowcount":
            return str(len(self.grid_rows()))
        scalar = self._scalar_value(path, member)
        if scalar is not None:
            return scalar
        self.misses.append((path, member))
        return f"[mock] {path}.{member}"

    # -- calls ------------------------------------------------------------
    def invoke_method(self, path: str, member: str, args: list) -> Any:
        m = member.lower()
        if m == "extractdata":
            return self.grid_rows()
        if m == "populategridview":
            grid_name = args[0] if args else "export"
            return self._write_export(self.export_rows(), "tempexport", f"{grid_name}.txt")
        if m == "getcellvalue" and len(args) >= 2:
            return self._cell_value(args[0], args[1])
        # sendVKey / press / select / setFocus / modifyCell / pressToolbarButton
        # and friends are accepted no-ops.
        return None

    # -- grid helpers -----------------------------------------------------
    def grid_rows(self, transaction: str | None = None) -> list[dict]:
        name = self._dataset_name("grid", transaction)
        if name is None:
            return []
        return self._datasets.get(name, [])

    def export_rows(self, transaction: str | None = None) -> list[dict]:
        name = self._dataset_name("export", transaction)
        if name is None:
            return []
        return self._datasets.get(name, [])

    def knows_column(self, column: str) -> bool:
        """True when any dataset carries this column (grid coverage check)."""
        return any(column in row for rows in self._datasets.values() for row in rows)

    def _cell_value(self, row: Any, column: str) -> str:
        try:
            row_idx = int(row)
        except (TypeError, ValueError):
            return ""
        rows = self.grid_rows()
        if not (0 <= row_idx < len(rows)):
            return ""
        value = rows[row_idx].get(column)
        if value is None:
            if not self.knows_column(column):
                self.misses.append(("getCellValue", str(column)))
            return ""
        return value

    def _write_export(self, data: list[dict], path: str, filename: str) -> str | None:
        if not data or not path or not filename:
            logger.warning("[fake] No data or path for export generation")
            return None
        if "*" in str(path) or "*" in str(filename):
            # The coverage replay passes normalised wildcards, not real paths.
            return None
        headers = list(data[0].keys())
        export_file = Path(path) / filename
        lines = ["\t".join(headers)]
        lines += ["\t".join(str(row.get(h, "")) for h in headers) for row in data]
        try:
            export_file.parent.mkdir(parents=True, exist_ok=True)
            export_file.write_text("\n".join(lines), encoding="utf-8")
        except OSError as exc:
            # e.g. a coverage replay passes the normalised "*" placeholder.
            logger.warning("[fake] Could not write export %s: %s", export_file, exc)
            return None
        return str(export_file)

    # -- scenario resolution ---------------------------------------------
    def _transaction_def(self, transaction: str | None = None) -> dict:
        txn = transaction or self.current_transaction
        return self._transactions.get(txn, {}) if txn else {}

    def _dataset_name(self, kind: str, transaction: str | None = None) -> str | None:
        name = self._transaction_def(transaction).get(kind, _MISSING)
        if name is _MISSING:
            name = self._defaults.get(kind, self._defaults.get("grid"))
        return name

    def _sbar_value(self, member: str) -> str:
        sbar = self._transaction_def().get("sbar", {})
        if member == "text":
            if self._upload_filename:
                return f"Document {self._upload_filename} was created successfully"
            return sbar.get("text", "No document was created")
        if member == "messagetype":
            if self._upload_filename:
                return "S"
            return sbar.get("type", "E")
        return ""

    def _scalar_value(self, path: str, member: str) -> Any:
        """First matching path-substring response across transactions.

        The current transaction is searched first, then the rest: some reads
        (the isolated os_read_* probes) run on a screen navigated by an
        earlier script, so the fake can't always infer the tcode from the
        read's own script.
        """
        if member.lower() != "text":
            return None
        current = self.current_transaction
        defs = []
        if current in self._transactions:
            defs.append(self._transactions[current])
        defs += [d for t, d in self._transactions.items() if t != current]
        for txn_def in defs:
            for substring, response in txn_def.get("scalars", {}).items():
                if substring and substring in path:
                    if isinstance(response, dict):
                        return response.get(member.lower(), "")
                    return response
        return None

    def _path_absent(self, path: str) -> bool:
        if self._transaction_def().get("grid", _MISSING) is None:
            # Grid explicitly nulled: the result list never renders, so the
            # export button is the first control that cannot be found.
            return _EXPORT_BUTTON_MARKER in path
        return False


class FakeElement:
    """A dynamically-resolved SAP control.

    ``getattr`` name-based dispatch is required because ``RealSapBackend``
    reaches properties with plain ``getattr`` and methods with
    ``getattr(...)(...)``; the fake must answer each shape correctly.
    """

    def __init__(self, session: FakeSession, path: str):
        object.__setattr__(self, "_session", session)
        object.__setattr__(self, "_path", path)

    def __getattr__(self, member: str) -> Any:
        if member.startswith("_"):
            raise AttributeError(member)
        if member.lower() in _METHOD_NAMES:
            return lambda *args: self._session.invoke_method(
                self._path, member, list(args)
            )
        return self._session.read_property(self._path, member)

    def __setattr__(self, member: str, value: Any) -> None:
        if member.startswith("_"):
            object.__setattr__(self, member, value)
            return
        self._session.write_property(self._path, member, value)
